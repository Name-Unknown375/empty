"""
Forever Party Rentals — idempotent nav/footer injector for hand-authored HTML.

Walks the listed .html files and inserts (or replaces) the static nav and
footer between sentinel comments:

  <!-- NAV:START -->...<!-- NAV:END -->     placed as first child of <body>
  <!-- FOOTER:START -->...<!-- FOOTER:END -->   placed before the trailing
                                                shared.js script tag

First run inserts the markers in the correct positions. Subsequent runs are
pure replacements between the markers — fully idempotent.

This script is intentionally NOT responsible for cache-bust version bumps.
Bump shared.js / shared.css versions with a separate sed pass:

  find site/ _build/ -type f \\( -name '*.html' -o -name '*.j2' \\) \\
       -exec sed -i -E 's|shared\\.(js|css)\\?v=OLD|shared.\\1?v=NEW|g' {} +

Decoupling keeps each concern (partial injection vs. cache-busting) reviewable
in isolation and prevents accidental version downgrades when re-running.

Generated pages (city / product / SKU / christmas / package) do NOT go through
this script — they get the same HTML via Jinja {% include %} in their
templates and the generator regenerates them. Only hand-authored files in
site/*.html and site/blog/*.html are touched here.

Usage:
  python3 _build/apply_partials.py site/contact.html site/index.html ...
  python3 _build/apply_partials.py --hand-authored
  python3 _build/apply_partials.py --blog
  python3 _build/apply_partials.py --all                     # both groups
  python3 _build/apply_partials.py --dry-run --all           # preview only

No Netlify or third-party dependencies. Python 3.8+ stdlib + Jinja2 (project dep).
"""
