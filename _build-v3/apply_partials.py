# Sentinel markers — content between them gets replaced on every run.
NAV_START = "<!-- NAV:START -->"
NAV_END = "<!-- NAV:END -->"
FOOTER_START = "<!-- FOOTER:START -->"
FOOTER_END = "<!-- FOOTER:END -->"


def _apply_nav(html: str, nav_html: str) -> str:
    block = f"{NAV_START}\n{nav_html}\n{NAV_END}"

    # Re-run case: replace whatever sits between the markers, preserving them.
    if NAV_START in html and NAV_END in html:
        return re.sub(
            re.escape(NAV_START) + r".*?" + re.escape(NAV_END),
            block,
            html,
            count=1,
            flags=re.DOTALL,
        )

    # First-run case: insert immediately after <body[ ...]>.
    body_match = re.search(r"<body\b[^>]*>", html)
    if not body_match:
        raise SystemExit("No <body> tag found; cannot insert nav.")
    insert_pos = body_match.end()
    return html[:insert_pos] + "\n" + block + html[insert_pos:]


def _apply_footer(html: str, footer_html: str) -> str:
    block = f"{FOOTER_START}\n{footer_html}\n{FOOTER_END}"

    if FOOTER_START in html and FOOTER_END in html:
        return re.sub(
            re.escape(FOOTER_START) + r".*?" + re.escape(FOOTER_END),
            block,
            html,
            count=1,
            flags=re.DOTALL,
        )

    # First-run: insert immediately before the trailing shared.js script tag.
    # Both `shared.js` and `../shared.js` accepted.
    script_re = re.compile(
        r"<script\s+src=\"(?:\.\./)?shared\.js\?v=\d+\"\s*></script>",
        re.IGNORECASE,
    )
    m = script_re.search(html)
    if not m:
        raise SystemExit(
            "No <script src=\".../shared.js?v=N\"></script> found; cannot insert footer."
        )
    return html[:m.start()] + block + "\n" + html[m.start():]


def process_file(path: Path, nav_html: str, footer_html: str, dry_run: bool = False) -> bool:
    """Returns True if the file was changed."""
    original = path.read_text(encoding="utf-8")
    updated = _apply_nav(original, nav_html)
    updated = _apply_footer(updated, footer_html)
    if updated == original:
        return False
    if not dry_run:
        path.write_text(updated, encoding="utf-8")
    return True


def collect_targets(args: argparse.Namespace) -> list[Path]:
    targets: list[Path] = []
    if args.all or args.hand_authored:
        targets.extend(SITE_DIR / rel for rel in HAND_AUTHORED)
    if args.all or args.blog:
        blog_dir = SITE_DIR / "blog"
        # Glob includes _template.html intentionally — future posts inherit the markers.
        blog_files = sorted(blog_dir.glob("*.html"))
        # Hand-authored set already includes blog/index.html; avoid duplicates.
        already = {SITE_DIR / "blog" / "index.html"}
        targets.extend(p for p in blog_files if p not in already)
    targets.extend(Path(p) for p in args.paths)
    # De-duplicate while preserving order.
    seen = set()
    deduped: list[Path] = []
    for t in targets:
        rp = t.resolve()
        if rp in seen:
            continue
        seen.add(rp)
        deduped.append(t)
    return deduped


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("paths", nargs="*", help="Specific files to process")
    ap.add_argument("--hand-authored", action="store_true", help="Process the 19 hand-authored pages")
    ap.add_argument("--blog", action="store_true", help="Process site/blog/*.html")
    ap.add_argument("--all", action="store_true", help="Process both groups")
    ap.add_argument("--dry-run", action="store_true", help="Show what would change, don't write")
    args = ap.parse_args()

    if not (args.paths or args.hand_authored or args.blog or args.all):
        ap.print_help()
        return 1

    targets = collect_targets(args)

    # Sanity-check the blog set against site/blog/posts.json (the manifest).
    # Catches accidentally-deleted post files OR posts.json drift. Fail loud.
    if args.all or args.blog:
        manifest_path = SITE_DIR / "blog" / "posts.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        expected_slugs = {p["slug"] for p in manifest["posts"]}
        on_disk = {p.stem for p in (SITE_DIR / "blog").glob("*.html")
                   if p.stem not in {"index", "_template"}}
        missing = expected_slugs - on_disk
        orphaned = on_disk - expected_slugs
        if missing:
            print(f"ERROR: posts.json lists {sorted(missing)} but those .html files are missing.")
            return 4
        if orphaned:
            print(f"ERROR: site/blog/ has {sorted(orphaned)}.html with no entry in posts.json.")
            return 4

    nav_html = render_nav()
    footer_html = render_footer()

    print(f"Targets: {len(targets)} file(s)")
    changed = unchanged = missing = 0
    for path in targets:
        if not path.exists():
            print(f"  MISSING: {path}")
            missing += 1
            continue
        try:
            if process_file(path, nav_html, footer_html, dry_run=args.dry_run):
                print(f"  {'would update' if args.dry_run else 'updated '} {path.relative_to(REPO_ROOT)}")
                changed += 1
            else:
                print(f"  unchanged  {path.relative_to(REPO_ROOT)}")
                unchanged += 1
        except SystemExit as e:
            print(f"  ERROR    {path.relative_to(REPO_ROOT)}: {e}")
            return 2

    suffix = " (dry-run)" if args.dry_run else ""
    print(f"\nDone{suffix}: {changed} changed, {unchanged} unchanged, {missing} missing.")
    return 0 if missing == 0 else 3


if __name__ == "__main__":
    sys.exit(main())
